package main

// Supervision of the GO Feature Flag relay proxy child process, the admin refresh, and the
// evaluation probe that makes /start, /change and /reset honour their contracts.

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"os"
	"os/exec"
	"sync"
	"time"
)

const (
	relayProxyBin = "/go-feature-flag"
	probeTimeout  = 30 * time.Second
	probeInterval = 50 * time.Millisecond
)

type relayProxy struct {
	mu     sync.Mutex
	cmd    *exec.Cmd
	exited chan struct{} // closed when cmd exits

	configPath string
	flagsPath  string
	port       int
	adminKey   string

	client *http.Client
}

func newRelayProxy(configPath, flagsPath string, port int, adminKey string) *relayProxy {
	return &relayProxy{
		configPath: configPath,
		flagsPath:  flagsPath,
		port:       port,
		adminKey:   adminKey,
		client:     &http.Client{Timeout: 5 * time.Second},
	}
}

// writeConfig renders goff-proxy.yaml. Settings that are deliberate:
//
//   - One file retriever. The launchpad owns that file; it is the whole "fake the config source".
//   - pollingInterval 1000 is GOFF's floor (lower values are clamped silently). The testbed does
//     not rely on polling at all -- /change and /reset call the admin refresh -- but polling at the
//     floor keeps a hand edit inside the container visible within a second.
//   - startWithRetrieverError false (the default), written out because the alternative is a relay
//     proxy that answers /health 200 while serving FLAG_NOT_FOUND for everything.
//   - An admin key and no evaluation keys: providers connect unauthenticated, the launchpad alone
//     can refresh.
func (p *relayProxy) writeConfig() error {
	cfg := fmt.Sprintf(`# Generated by the launchpad at container start. Do not edit.
server:
  mode: http
  port: %d
retrievers:
  - kind: file
    path: %s
fileFormat: json
pollingInterval: 1000
startWithRetrieverError: false
authorizedKeys:
  admin:
    - %s
`, p.port, p.flagsPath, p.adminKey)
	return os.WriteFile(p.configPath, []byte(cfg), 0o644)
}

func (p *relayProxy) running() bool {
	p.mu.Lock()
	defer p.mu.Unlock()
	return p.cmd != nil
}

// start launches the relay proxy. It does NOT wait for readiness; callers probe for that.
func (p *relayProxy) start() error {
	p.mu.Lock()
	defer p.mu.Unlock()
	if p.cmd != nil {
		return nil
	}
	cmd := exec.Command(relayProxyBin, "--config", p.configPath)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Start(); err != nil {
		return fmt.Errorf("starting %s: %w", relayProxyBin, err)
	}
	exited := make(chan struct{})
	p.cmd, p.exited = cmd, exited
	go func() {
		_ = cmd.Wait() // reap; launchpad is PID 1
		// Clear before signalling, so a start() right after stop() returns sees no process.
		p.mu.Lock()
		if p.cmd == cmd {
			p.cmd = nil
		}
		p.mu.Unlock()
		close(exited)
	}()
	return nil
}

// stop kills the relay proxy process and waits for it to be reaped, so the port is free for a
// fast /restart. The container keeps running -- the control API is explicit that an outage MUST
// NOT stop the container, because dynamically mapped host ports do not survive it.
func (p *relayProxy) stop() error {
	p.mu.Lock()
	cmd, exited := p.cmd, p.exited
	p.mu.Unlock()
	if cmd == nil {
		return nil
	}
	if err := cmd.Process.Kill(); err != nil && !errors.Is(err, os.ErrProcessDone) {
		return err
	}
	select {
	case <-exited:
		return nil
	case <-time.After(5 * time.Second):
		return fmt.Errorf("relay proxy did not exit within 5s of SIGKILL")
	}
}

// refresh asks the relay proxy to re-read its retrievers now.
//
// POST /admin/v1/retriever/refresh is synchronous up to "served" (0 stale reads in 100 trials,
// FINDINGS.md #6), but its body is not a change signal: {"refreshed": true} also comes back
// when nothing changed, and {"refreshed": false} when the file is unreadable, in which case the
// last good flag set keeps being served. So a false is an error, a true proves nothing, and the
// probe that follows is what actually establishes the new state.
func (p *relayProxy) refresh() error {
	req, err := http.NewRequest(http.MethodPost, p.url("/admin/v1/retriever/refresh"), nil)
	if err != nil {
		return err
	}
	req.Header.Set("X-API-Key", p.adminKey)
	resp, err := p.client.Do(req)
	if err != nil {
		return fmt.Errorf("admin refresh: %w", err)
	}
	defer resp.Body.Close()
	body, _ := io.ReadAll(resp.Body)
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("admin refresh: status %d: %s", resp.StatusCode, body)
	}
	var r struct {
		Refreshed bool `json:"refreshed"`
	}
	if err := json.Unmarshal(body, &r); err != nil {
		return fmt.Errorf("admin refresh: %w", err)
	}
	if !r.Refreshed {
		return fmt.Errorf("admin refresh: retriever failed, relay proxy kept its previous flags")
	}
	return nil
}

type ofrepResponse struct {
	Key       string          `json:"key"`
	Value     json.RawMessage `json:"value"`
	Reason    string          `json:"reason"`
	Variant   string          `json:"variant"`
	ErrorCode string          `json:"errorCode"`
}

// evaluate performs a real evaluation through the relay proxy's OFREP endpoint, exactly as a
// remote provider would.
func (p *relayProxy) evaluate(key string) (*ofrepResponse, error) {
	body := []byte(`{"context":{"targetingKey":"launchpad-probe"}}`)
	resp, err := p.client.Post(p.url("/ofrep/v1/evaluate/flags/"+key), "application/json", bytes.NewReader(body))
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	b, _ := io.ReadAll(resp.Body)
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("evaluate %s: status %d: %s", key, resp.StatusCode, b)
	}
	var r ofrepResponse
	if err := json.Unmarshal(b, &r); err != nil {
		return nil, fmt.Errorf("evaluate %s: %w", key, err)
	}
	return &r, nil
}

// probeServing blocks until the relay proxy actually serves `want` for `key`, or the deadline
// passes, or the process dies.
//
// This is the requirement /start exists to satisfy (flagd-testbed#394). GOFF itself has no
// early-ready window -- it loads the retriever before binding the port -- so on a good start this
// returns on the first or second attempt. It stays because the contract is "serving", not
// "healthy", and because the failure it does catch is real: GOFF exits with status 0 when it cannot
// read its flag file, which nothing but a probe would notice.
func (p *relayProxy) probeServing(key string, want json.RawMessage, timeout time.Duration) error {
	p.mu.Lock()
	exited := p.exited
	p.mu.Unlock()

	deadline := time.Now().Add(timeout)
	var last error
	for time.Now().Before(deadline) {
		r, err := p.evaluate(key)
		switch {
		case err != nil:
			last = err
		case jsonEqual(r.Value, want):
			return nil
		default:
			last = fmt.Errorf("evaluate %s: serving %s, want %s", key, r.Value, want)
		}
		if exited != nil {
			select {
			case <-exited:
				return fmt.Errorf("relay proxy exited while waiting for %s (see container logs): %w", key, last)
			default:
			}
		}
		time.Sleep(probeInterval)
	}
	return fmt.Errorf("timed out after %s waiting for %s: %w", timeout, key, last)
}

func (p *relayProxy) url(path string) string {
	return fmt.Sprintf("http://127.0.0.1:%d%s", p.port, path)
}

func jsonEqual(a, b json.RawMessage) bool {
	var av, bv any
	if json.Unmarshal(a, &av) != nil || json.Unmarshal(b, &bv) != nil {
		return false
	}
	ab, _ := json.Marshal(av)
	bb, _ := json.Marshal(bv)
	return bytes.Equal(ab, bb)
}
